"""Generate the shared Gleworks theme adapters from theme/tokens.json.

Outputs:
  os/ui/gw_theme_tokens.h
  apps/koreader/overlay/opt/koreader/plugins/gw-theme.koplugin/gw_theme.lua

Run from anywhere:
  python3 theme/generate.py
  python3 theme/generate.py --check
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "theme" / "tokens.json"
C_HEADER = ROOT / "os" / "ui" / "gw_theme_tokens.h"
LUA_MODULE = (
    ROOT
    / "apps"
    / "koreader"
    / "overlay"
    / "opt"
    / "koreader"
    / "plugins"
    / "gw-theme.koplugin"
    / "gw_theme.lua"
)

BANNER = "Generated by theme/generate.py from theme/tokens.json. Do not edit."


def rgb(hex_color: str) -> tuple[int, int, int]:
    value = hex_color.lstrip("#")
    if len(value) != 6:
        raise ValueError(f"expected #RRGGBB, got {hex_color!r}")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def gray(hex_color: str) -> int:
    r, g, b = rgb(hex_color)
    if r != g or g != b:
        raise ValueError(f"theme colour must be grayscale for E-ink: {hex_color!r}")
    return r


def render_c(t: dict) -> str:
    c = t["color"]
    s = t["space"]
    ty = t["type"]
    r = t["radius"]
    st = t["stroke"]
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later",
        f" * {BANNER}",
        " */",
        "#ifndef GW_THEME_TOKENS_H",
        "#define GW_THEME_TOKENS_H",
        "",
        "#include <lvgl/lvgl.h>",
        "",
        "/* Canvas */",
        f"#define GW_UI_PANEL_W          {t['meta']['design_width']}",
        f"#define GW_UI_PANEL_H          {t['meta']['design_height']}",
        "",
        "/* Spacing, in physical pixels for the design canvas. */",
        f"#define GW_UI_MARGIN           {s['margin']}",
        f"#define GW_UI_GAP              {s['gap']}",
        f"#define GW_UI_SECTION_GAP      {s['section_gap']}",
        f"#define GW_UI_CARD_PADDING     {s['card_padding']}",
        f"#define GW_UI_TOUCH_MIN        {s['touch_min']}",
        f"#define GW_UI_STATUS_BAR_H     {s['status_bar_h']}",
        f"#define GW_UI_NAV_BAR_H        {s['nav_bar_h']}",
        f"#define GW_UI_APP_BAR_H        {s['app_bar_h']}",
        "",
        "/* Spacing scale: 8 / 16 / 24 / 32 / 48 px only. */",
        f"#define GW_UI_SPACE_1          {s['space_1']}",
        f"#define GW_UI_SPACE_2          {s['space_2']}",
        f"#define GW_UI_SPACE_3          {s['space_3']}",
        f"#define GW_UI_SPACE_4          {s['space_4']}",
        f"#define GW_UI_SPACE_6          {s['space_6']}",
        "",
        "/* Type scale, retained here so both adapters share one source. */",
        f"#define GW_UI_TYPE_HERO        {ty['hero']}",
        f"#define GW_UI_TYPE_TITLE       {ty['title']}",
        f"#define GW_UI_TYPE_BODY        {ty['body']}",
        f"#define GW_UI_TYPE_CAPTION     {ty['caption']}",
        f"#define GW_UI_TYPE_SECTION     {ty['section']}",
        f"#define GW_UI_TYPE_CLOCK       {ty['clock']}",
        "",
        "/* Shape */",
        f"#define GW_UI_CARD_RADIUS      {r['card']}",
        f"#define GW_UI_TEXTAREA_RADIUS  {r['textarea']}",
        f"#define GW_UI_HAIRLINE         {st['hairline']}",
        "",
        "/* Derived layout */",
        "#define GW_UI_COL_W            ((GW_UI_PANEL_W - 2 * GW_UI_MARGIN - GW_UI_GAP) / 2)",
        "#define GW_UI_CONTENT_W        (GW_UI_PANEL_W - 2 * GW_UI_MARGIN)",
        "#define GW_UI_QUICK_W          ((GW_UI_CONTENT_W - 3 * GW_UI_GAP) / 4)",
        "",
        "/* Grayscale colours */",
    ]
    for name in ("bg", "text", "secondary", "muted", "border", "card"):
        rr, gg, bb = rgb(c[name])
        lines.append(
            f"static inline lv_color_t gw_ui_c_{name}(void) "
            f"{{ return lv_color_make({rr}, {gg}, {bb}); }}"
        )
    lines += [
        "static inline lv_color_t gw_ui_c_white(void) { return gw_ui_c_bg(); }",
        "",
        "#endif /* GW_THEME_TOKENS_H */",
        "",
    ]
    return "\n".join(lines)


def render_lua(t: dict) -> str:
    c = t["color"]
    s = t["space"]
    ty = t["type"]
    r = t["radius"]
    st = t["stroke"]
    f = t["font"]
    reader = t["reader"]
    lines = [
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        f"-- {BANNER}",
        "return {",
        f'  meta = {{ name = "{t["meta"]["name"]}", version = {t["meta"]["version"]}, '
        f'design_width = {t["meta"]["design_width"]}, design_height = {t["meta"]["design_height"]} }},',
        "  color = {",
    ]
    for name in ("bg", "text", "secondary", "muted", "border", "card"):
        lines.append(f'    {name} = 0x{gray(c[name]):02X}, -- {c[name]}')
    lines += [
        "  },",
        "  space = {",
    ]
    for name in ("margin", "gap", "section_gap", "card_padding", "touch_min",
                 "status_bar_h", "nav_bar_h", "app_bar_h",
                 "space_1", "space_2", "space_3", "space_4", "space_6"):
        lines.append(f"    {name} = {s[name]},")
    lines += [
        "  },",
        "  type = {",
    ]
    for name in ("hero", "title", "body", "caption", "section", "clock"):
        lines.append(f"    {name} = {ty[name]},")
    lines += [
        "  },",
        f"  radius = {{ card = {r['card']}, textarea = {r['textarea']} }},",
        f"  stroke = {{ hairline = {st['hairline']} }},",
        f'  font = {{ ui = "{f["ui"]}", reader = "{f["reader"]}" }},',
        "  reader = {",
    ]
    for name in ("font_size", "line_spacing", "page_margin_lr", "page_margin_tb",
                 "footer_font_size", "footer_height", "footer_bottom_padding"):
        lines.append(f"    {name} = {reader[name]},")
    lines += [
        "  },",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv[1:]
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    outputs = {
        C_HEADER: render_c(t),
        LUA_MODULE: render_lua(t),
    }
    stale = []
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                stale.append(path)
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if check:
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("theme adapters are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
